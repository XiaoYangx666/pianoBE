import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const addon = fileURLToPath(new URL("../../../packages/addon/src/data/", import.meta.url));

/** Read an `export const NAME = <literal> as const;` declaration from a generated TS module. */
function readLiteral(fileName, name) {
    const source = readFileSync(join(addon, fileName), "utf8");
    const marker = `export const ${name} =`;
    const start = source.indexOf(marker);
    if (start < 0) throw new Error(`Missing ${name} in ${fileName}`);
    let index = start + marker.length;
    while (/\s/.test(source[index])) index++;
    if (source[index] !== "[" && source[index] !== "{") throw new Error(`Unsupported literal for ${name}`);
    const open = source[index];
    const close = open === "[" ? "]" : "}";
    let depth = 0;
    const from = index;
    for (; index < source.length; index++) {
        if (source[index] === open) depth++;
        else if (source[index] === close && --depth === 0) break;
    }
    return JSON.parse(source.slice(from, index + 1).replace(/,\s*([\]}])/g, "$1"));
}

function tailOf(parts) {
    return parts.reduce((tail, part) => Math.max(tail, -(part.forward ?? 0)), 0);
}

/**
 * VFX owns the shared key layout and stage frame used by both Bedrock and the Web
 * preview. The raw model data still lives in the addon's generated modules, so this
 * document is regenerated from them by `build-vfx-lab.mjs` instead of being edited.
 */
export function buildKeyDocument() {
    const upright = readLiteral("hitboxes.generated.ts", "KEY_HITBOXES");
    const uprightLine = readLiteral("hitboxes.generated.ts", "PIANO_PARTICLE_LINE");
    const grand = readLiteral("grand.generated.ts", "GRAND_KEY_HITBOXES");
    const grandLine = readLiteral("grand.generated.ts", "GRAND_PARTICLE_LINE");
    const parts = readLiteral("grand.generated.ts", "GRAND_PARTS");
    return `// Generated by tools/assets/build-vfx-lab.mjs from the addon's model data. Do not edit.\n` +
        `export const UPRIGHT_KEY_HITBOXES = ${JSON.stringify(upright)} as const;\n\n` +
        `export const GRAND_KEY_HITBOXES = ${JSON.stringify(grand)} as const;\n\n` +
        `export const UPRIGHT_PARTICLE_LINE = ${JSON.stringify(uprightLine)} as const;\n\n` +
        `export const GRAND_PARTICLE_LINE = ${JSON.stringify(grandLine)} as const;\n\n` +
        `export const UPRIGHT_STAGE_TAIL = 0;\n\n` +
        `export const GRAND_STAGE_TAIL = ${tailOf(parts)};\n`;
}
